"""Generate the Reforged controls preset from the saved Forge options inventory."""

from pathlib import Path

HERE = Path(__file__).resolve().parent
PRESET = HERE.parents[1] / "launcher/controls-preset.txt"
UNKNOWN = "key.keyboard.unknown"
KEYBOARD = "key.keyboard."

# The saved 1.20.1 vanilla assignments are the first 34 rows of the inventory.
VANILLA_LAST = "key_key.hotbar.9"
PRIORITY = {
    "key_key.ftbchunks.map": "m",
    "key_key.ftbquests.quests": "b",
    "key_key.ftbultimine": "grave.accent",
    "key_key.jei.showRecipe": "r",
    "key_key.jei.showUses": "u",
    "key_key.jei.closeRecipeGui": "escape",
    "key_key.jei.bookmark": "y",
    "key_key.sophisticatedbackpacks.open_backpack": "g",
    "key_key.curios.open.desc": "h",
    "key_key.guideme.guide": "f6",
    "key_create.keyinfo.toolmenu": "left.alt",
    "key_create.keyinfo.toolbelt": "right.alt",
    "key_pneumaticcraft.boots.jet_boots": "keypad.enter",
    "key_key.electrodynamics.jetpackascend": "keypad.add",
    "key_oreexcavation.key.excavate": "right.control",
    "key_key.jade.show_details": "right.shift",
}
RESERVED = {KEYBOARD + key for key in ("f1", "f3", "f4", "left.win", "right.win", "print.screen")}
SECONDARY = (
    "key.keyboard.keypad.6", "key.keyboard.keypad.7", "key.keyboard.keypad.subtract",
    "key.keyboard.keypad.multiply", "key.keyboard.keypad.divide", "key.keyboard.keypad.decimal",
    "key.keyboard.insert", "key.keyboard.delete", "key.keyboard.home", "key.keyboard.end",
    "key.keyboard.f8", "key.keyboard.f10", "key.keyboard.caps.lock",
    "key.mouse.5", "key.mouse.6", "key.mouse.7", "key.mouse.8",
)


def read_bindings(path):
    entries = {}
    for line in path.read_text(encoding="utf-8").splitlines():
        if not line or line.startswith("#"):
            continue
        name, value = line.split(":", 1)
        if not name.startswith("key_") or not value or name in entries:
            raise ValueError(f"Invalid or repeated binding: {line}")
        entries[name] = value
    return entries


def vanilla(inventory):
    names = list(inventory)
    return {name: inventory[name] for name in names[:names.index(VANILLA_LAST) + 1]}


def layout(inventory):
    assigned = vanilla(inventory)
    for name, key in PRIORITY.items():
        if name not in inventory:
            raise ValueError(f"Priority mapping is absent: {name}")
        assigned[name] = KEYBOARD + key
    active = [key for key in assigned.values() if key != UNKNOWN]
    if len(active) != len(set(active)):
        raise ValueError("Priority assignments collide")
    used = set(active) | RESERVED
    deferred = []
    for name, original in inventory.items():
        if name in assigned:
            continue
        physical = original.split(":", 1)[0]
        if physical == UNKNOWN:
            assigned[name] = UNKNOWN
        elif physical not in used and ":" not in original:
            assigned[name] = physical
            used.add(physical)
        else:
            deferred.append(name)
    # Assign spare keys to frequently used shortcuts before utility and debug actions.
    preferred = (
        "keybind.ironjetpacks.", "key_key.mekanism.", "key_key.ars_nouveau.",
        "key_tfmg.", "key_pneumaticcraft.", "key_key.buildinggadgets2.",
        "key_key.draconicevolution.", "key_key.jei.", "key_key.sophisticated",
    )
    def priority(name):
        return next((i for i, prefix in enumerate(preferred) if prefix in name), len(preferred))
    spare = iter(key for key in SECONDARY if key not in used)
    for name in sorted(deferred, key=priority):
        assigned[name] = next(spare, UNKNOWN)
    return {name: assigned[name] for name in inventory}


def render(bindings):
    return ("# Antimatter Chemistry Reforged 2.0.3 / Forge 47.4.10\n"
            "# Generated by tools/keybinds/build_preset.py\n" +
            "".join(f"{name}:{key}\n" for name, key in bindings.items())).encode()


if __name__ == "__main__":
    PRESET.write_bytes(render(layout(read_bindings(HERE / "registered-keys.txt"))))
